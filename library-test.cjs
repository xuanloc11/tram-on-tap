const assert = require('node:assert/strict');
require('./dist/questions-1-2.js');
require('./dist/questions-3.js');
require('./dist/questions-4-5.js');
const E = require('./dist/engine');
const L = require('./dist/library');
const bank = [...QUESTION_PART_12, ...QUESTION_PART_3, ...QUESTION_PART_45];
const original = L.createDefault(bank, E.CHAPTERS);
assert.equal(L.validate(original), true);
assert.equal(original.questions.length, 168);
assert.equal(original.exams.length, 12);
assert.equal(new Set(original.subjects.flatMap(s => s.chapters.map(c => c.id))).size, 5);
const ids = new Set(original.exams.slice(0,6).flatMap(exam => E.makeAttempt(original.questions, {
  ...exam, label: exam.name, chapters: original.subjects[0].chapters, now: 1000
}).questions.map(q => q.id)));
assert.equal(ids.size, 168, 'The first six default exams cover the full bank');
const empty = { version: 2, subjects: [{ id: 'new-subject', name: 'Môn mới', chapters: [] }], questions: [], exams: [] };
assert.equal(L.validate(empty), true, 'An empty new subject can be saved');
assert.throws(() => L.validate({ ...empty, subjects: [] }), /ít nhất một môn/);
function reject(change, pattern) { const value = L.clone(original); change(value); assert.throws(() => L.validate(value), pattern); }
reject(data => { data.questions[0].id = data.subjects[0].id; }, /trùng/);
reject(data => { data.subjects[0].id = '__proto__'; }, /không hợp lệ/);
reject(data => { data.subjects[0].name = ' '; }, /tên/);
reject(data => { data.subjects[0].examDate = '2026-02-31'; }, /ngày tồn tại/);
reject(data => { data.subjects[0].chapters[1].id = 1; }, /mã trùng/);
reject(data => { data.questions[0].subjectId = 'missing'; }, /tồn tại/);
reject(data => { data.questions[0].chapter = 99; }, /tồn tại/);
reject(data => { data.questions[0].options[0] = data.questions[0].options[1] + ' '; }, /khác nhau/);
reject(data => { data.questions[0].answer = '0'; }, /đáp án đúng/);
reject(data => { data.exams[0].durationMinutes = 0; }, /1–180/);
reject(data => { data.exams[0].seed = -1; }, /mã trộn/);
reject(data => { data.exams[0].chapterCounts[0].count = 99; }, /chưa đủ/);
reject(data => { data.exams[0].chapterCounts.push({ chapterId: 1, count: 1 }); }, /không trùng/);

const chapters = [{ id: 10, title: 'Động học', short: 'Động học', color: 'blue' }, { id: 20, title: 'Động lực học', short: 'Động lực học', color: 'sage' }];
const physics = [10,10,10,20,20].map((chapter, i) => ({ id: 'physics-q-' + i, subjectId: 'physics', chapter, question: 'Câu vật lý ' + i, options: ['Đúng', 'Sai một', 'Sai hai', 'Sai ba'], answer: 0, explanation: '', source: '' }));
const data = L.clone(original);
data.subjects.push({ id: 'physics', name: 'Vật lý đại cương', code: 'PHYS', chapters });
data.questions.push(...physics);
const config = { id: 'physics-exam', subjectId: 'physics', name: 'Luyện Vật lý', seed: 42, durationMinutes: 7, chapterCounts: [{ chapterId: 10, count: 2 }, { chapterId: 20, count: 1 }] };
data.exams.push(config);
assert.equal(L.validate(data), true);
const a = E.makeAttempt(data.questions, { ...config, label: config.name, subjectName: 'Vật lý đại cương', chapters, now: 5000 });
assert.equal(a.questions.length, 3);
assert.equal(a.deadline, 425000);
assert.equal(E.remaining(a, 5000), 420);
assert.equal(E.isValidAttempt(a, []), true, 'Snapshot attempts do not need the current bank');
assert(a.questionSnapshots.every(q => q.subjectId === 'physics'));
assert.deepEqual(a.chapterCounts, config.chapterCounts);
a.questions.forEach(q => { a.answers[q.id] = 0; });
assert.equal(E.grade(a, []).score, 10);
data.questions.forEach(q => { q.answer = 1; q.options[0] = 'Đã sửa'; });
data.subjects.find(s => s.id === 'physics').chapters[0].title = 'Tên chương mới';
assert.equal(E.grade(a, data.questions).score, 10, 'Editing questions cannot change past scores');
assert.equal(E.grade(a, []).chapters[0].title, 'Động học', 'Chapter names remain as they were during the attempt');
assert.equal(a.questionSnapshots[0].options[0], 'Đúng', 'Question options are a deep snapshot');
const b = JSON.parse(JSON.stringify(a));
assert.equal(E.isValidAttempt(b, []), true);
assert.equal(E.grade(b, []).score, 10);
b.questionSnapshots[0].answer = 5;
assert.equal(E.isValidAttempt(b, []), false);
const badCounts = L.clone(a); badCounts.chapterCounts[0].count = 1;
assert.equal(E.isValidAttempt(badCounts, []), false);
const missingSnapshot = L.clone(a); missingSnapshot.questionSnapshots = null;
assert.equal(E.isValidAttempt(missingSnapshot, physics), false);
assert.throws(() => E.makeAttempt(physics, { seed: 1, subjectId: 'physics', chapters, chapterCounts: [{ chapterId: 20, count: 3 }] }), /chỉ có 2/);
assert.throws(() => E.makeAttempt([], { seed: 1, subjectId: 'physics', chapters, mode: 'practice', chapter: 10 }), /chưa có câu hỏi/);
assert.throws(() => E.makeAttempt(physics, { seed: 1, subjectId: 'physics', chapters, chapterCounts: [{ chapterId: 10, count: 1 }], durationMinutes: 181 }), /1 đến 180/);
assert.throws(() => E.makeAttempt(physics, { seed: 1, subjectId: 'physics', chapters: [] }), /không hợp lệ/);
const practice = E.makeAttempt(physics, { seed: 1, subjectId: 'physics', subjectName: 'Vật lý', chapters, mode: 'practice', chapter: 20, now: 5000 });
assert.equal(practice.questions.length, 2);
assert.equal(practice.deadline, null);
assert.equal(E.isValidAttempt(practice, []), true);

const legacy = E.makeAttempt(bank, { seed: 777, now: 10000 });
for (const key of ['questionSnapshots','chapterSnapshots','chapterCounts','subjectId','subjectName','durationMinutes','examId']) delete legacy[key];
legacy.current = 2; legacy.answers[legacy.questions[0].id] = bank.find(q => q.id === legacy.questions[0].id).answer;
assert.equal(E.isValidAttempt(legacy, bank), true);
const migrated = E.upgradeAttempt(legacy, bank);
assert.equal(migrated.id, legacy.id);
assert.equal(migrated.current, 2);
assert.equal(migrated.deadline, legacy.deadline);
assert.deepEqual(migrated.answers, legacy.answers);
assert.equal(E.isValidAttempt(migrated, []), true);
assert.equal(E.grade(migrated, []).correct, 1);
assert.equal(E.upgradeAttempt(null, bank), null);
assert.notEqual(E.upgradeAttempt(migrated, []), migrated, 'Migration does not mutate its argument');
assert.equal(legacy.questionSnapshots, undefined);
console.log('PASS library: defaults, empty subjects, import validation, generic exams, subject isolation, custom duration, short practice, immutable history and legacy migration.');
